const c = (idle: string, step?: string): SpriteSet => {
  const parse = (art: string) => Object.freeze(art.trim().split("\n").map(row => row.trim().padEnd(16, ".").slice(0, 16)));
  const a = parse(idle);
  return Object.freeze({ idle: a, step: step ? parse(step) : a });
};
